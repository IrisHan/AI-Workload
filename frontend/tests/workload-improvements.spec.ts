import { test, expect } from "@playwright/test";

const evidence = process.env.PLANNER_E2E_EVIDENCE ?? "../data/workload-e2e";
test("compact inputs, hardware units, live metrics and persistent reuse", async ({ page, request }, info) => {
  test.setTimeout(90000);
  page.setDefaultTimeout(10000);
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  const models = await (await request.get("/api/models")).json();
  const model = models.find((m: { repo_id: string }) => m.repo_id === "Qwen/Qwen2.5-0.5B");
  const name = `Compact reuse ${info.project.name} ${Date.now()}`;
  await page.goto(`/workloads/inference/new?model=${model.id}&hardware=nvidia-a100-sxm-80gb-20260913`);
  if (info.project.name === "desktop") await page.setViewportSize({ width: 1366, height: 768 });
  await expect(page.getByRole("button", { name: "Params", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByLabel("Model parameter ledger")).toContainText("Architecture");
  await page.getByLabel("Design Name").fill(name);
  if (info.project.name === "mobile") await page.getByRole("button", { name: "Parameters", exact: true }).click();
  await expect(page.getByLabel("Intra Injection (GB/s)", { exact: true })).toHaveValue("300");
  await expect(page.getByLabel("Inter / GPU (GB/s)", { exact: true })).toHaveValue("25");
  await expect(page.locator(".wc-hardware-facts").first()).toContainText("2,039");
  await expect(page.getByLabel("Allowed TP", { exact: true })).not.toHaveValue("");
  await expect(page.getByLabel("Allowed PP", { exact: true })).not.toHaveValue("");
  await page.getByLabel("Activation Precision", { exact: true }).selectOption("fp32");
  await expect(page.locator(".wc-hardware-facts").first()).toContainText("19.5");
  await page.getByLabel("Activation Precision", { exact: true }).selectOption("bf16");
  await page.getByLabel("Activation Efficiency", { exact: true }).fill("0.85");
  await page.getByRole("button", { name: "Override · Reset", exact: true }).click();
  await expect(page.getByLabel("Activation Efficiency", { exact: true })).toHaveValue("1");
  await page.getByLabel("Intra Injection (GB/s)", { exact: true }).fill("123.5");
  await page.getByText("Topology Overrides & Source Notes", { exact: true }).click();
  await page.getByRole("button", { name: "恢复拓扑默认值", exact: true }).click();
  await expect(page.getByLabel("Intra Injection (GB/s)", { exact: true })).toHaveValue("300");
  await page.getByText("Topology Overrides & Source Notes", { exact: true }).click();
  await page.getByLabel("Intra Injection (GB/s)", { exact: true }).fill("123.5");
  await page.getByLabel("Mode", { exact: true }).selectOption("offline");
  await page.getByLabel("Prompt Tokens", { exact: true }).fill("5");
  await page.getByLabel("Output Tokens", { exact: true }).fill("3");
  await page.getByLabel("Concurrency", { exact: true }).fill("2");
  await page.getByLabel("Batch Size", { exact: true }).fill("2");
  await page.getByLabel("Request Count", { exact: true }).fill("2");
  await page.getByLabel("Search Mode", { exact: true }).selectOption("manual");
  await page.getByLabel("TP", { exact: true }).fill("2");
  await page.getByRole("button", { name: "Evaluate", exact: true }).click();
  await expect(page.locator(".wc-run-status")).toContainText("completed", { timeout: 45000 });
  const url = new URL(page.url());
  const designId = url.pathname.split("/").at(-1)!;
  const runId = url.searchParams.get("run")!;
  const saved = await (await request.get(`/api/workloads/designs/${designId}`)).json();
  expect(saved.revision.input.resources.topology_overrides.intra_bandwidth_bytes_s).toBe(123.5e9);
  expect(saved.runs[0].id).toBe(runId);
  if (info.project.name === "mobile") await page.getByRole("button", { name: "Results", exact: true }).click();
  await expect(page.getByLabel("Decision Summary")).toContainText("ms");
  await expect(page.getByLabel("Decision Summary")).toContainText("tokens/s");
  await expect(page.locator(".wc-execution-summary")).toContainText("Decision Summary");
  await page.getByText("Secondary Metrics", { exact: true }).click();
  await expect(page.getByLabel("Live Results", { exact: true })).toContainText("Window MFU");
  await page.goto(url.pathname);
  await expect(page.locator(".wc-run-status")).toContainText("completed");
  await expect(page.getByLabel("Run History")).toHaveValue(runId);
  if (info.project.name === "desktop") {
    for (const width of [1280, 1366, 1440]) {
      await page.setViewportSize({ width, height: 768 });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
      await page.screenshot({ path: `${evidence}/compact-${width}.png`, fullPage: true });
    }
  } else {
    await page.getByRole("button", { name: "Results", exact: true }).click();
    await page.screenshot({ path: `${evidence}/compact-mobile.png`, fullPage: true });
  }
  await page.getByLabel("Run History").selectOption("");
  await expect(page.locator(".wc-run-status")).toContainText("Ready");
  await page.reload();
  await expect(page.getByLabel("Run History")).toHaveValue("");
  await page.getByRole("button", { name: "Save as New Design", exact: true }).click();
  await expect(page).not.toHaveURL(new RegExp(`${designId}`));
  const forkId = new URL(page.url()).pathname.split("/").at(-1)!;
  expect(forkId).not.toBe("new");
  const fork = await (await request.get(`/api/workloads/designs/${forkId}`)).json();
  expect(fork.revision.input).toEqual(saved.revision.input);
  expect(fork.runs).toEqual([]);
  await page.goto("/workloads");
  await page.getByLabel("Search Designs").fill(name);
  await expect(page.locator(".wc-list tbody tr")).toHaveCount(2);
  await expect(page.locator(".wc-list tbody")).toContainText("A100");
  await page.getByLabel("Search Designs").fill("no-design-matches-this-name");
  await expect(page.getByText("No matching designs.", { exact: false })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});
