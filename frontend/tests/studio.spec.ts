import { test, expect } from "@playwright/test";
import fs from "node:fs/promises";

const evidence = process.env.PLANNER_E2E_EVIDENCE ?? "../docs/reports/2026-09-13-spec-studio-transplant/evidence";
const model = "2cb255f7a2a546a14e2923f7";

test("transplanted studio deep link, graph, options, history and model isolation", async ({ page, request }, info) => {
  const errors: string[] = [];
  const requests: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", req => requests.push(req.url()));
  await page.goto(`/models/${model}?tab=structure&group=g1&module=rope_k`);
  const studio = page.getByRole("region", { name: "Spec Studio model workspace" });
  await expect(studio.getByRole("heading", { name: "rope_k", exact: true })).toBeVisible();
  await expect(studio.locator(".metrics-strip")).toContainText("1,543,714,304");
  await expect(studio.locator(".metrics-strip")).toContainText("28,672 B");
  await page.screenshot({ path: `${evidence}/studio-deeplink-${info.project.name}.png`, fullPage: true });
  const close = studio.getByRole("button", { name: "关闭详情" });
  if (await close.isVisible()) await close.click();
  await expect(studio.locator(".react-flow__node").first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width + 1);
  if (info.project.name === "desktop") {
    const hierarchyBounds = await studio.locator(".hierarchy").boundingBox();
    const studioBounds = await studio.boundingBox();
    expect(hierarchyBounds!.x).toBe(studioBounds!.x);
    expect((await studio.locator(".flow-wrap").boundingBox())!.width).toBeGreaterThan(500);
  }
  await studio.getByRole("button", { name: "FFN", exact: true }).click();
  await expect(studio.locator(".react-flow__node").filter({ hasText: "gate_proj" })).toHaveCount(1);
  await studio.getByRole("button", { name: "Attention", exact: true }).click();
  await expect(studio.locator('.react-flow__node[data-id="q_proj"]')).toBeVisible();
  await studio.getByRole("button", { name: "放大", exact: true }).click();
  await studio.getByRole("button", { name: "适配画布", exact: true }).click();
  await studio.locator('.react-flow__node[data-id="q_proj"]').click();
  await expect(studio.getByTestId("module-detail")).toContainText("2,360,832");
  if (await close.isVisible()) await close.click();
  const hierarchy = studio.getByRole("button", { name: "层级", exact: true });
  if (await hierarchy.isVisible()) await hierarchy.click();
  await studio.locator("summary").filter({ hasText: "实例分页" }).click();
  await studio.getByRole("button", { name: "下一页实例" }).click();
  await studio.getByRole("button", { name: "L27 g1", exact: true }).click();
  await expect(page).toHaveURL(/layer=27/);
  await page.screenshot({ path: `${evidence}/studio-graph-${info.project.name}.png`, fullPage: true });
  const before = new URL(page.url()).searchParams.get("snapshot")!;
  await studio.getByLabel("KV dtype", { exact: true }).selectOption("fp32");
  await studio.getByRole("button", { name: "应用配置" }).click();
  await expect(studio.locator(".metrics-strip")).toContainText("57,344 B");
  await expect(page).toHaveURL(/kv_dtype=fp32/);
  const after = new URL(page.url()).searchParams.get("snapshot")!;
  expect(after).not.toBe(before);
  await studio.getByLabel("结构历史快照").selectOption(before);
  await expect(studio.locator(".metrics-strip")).toContainText("28,672 B");
  await expect(page).toHaveURL(/kv_dtype=bf16/);
  await studio.getByRole("button", { name: "参数账本", exact: true }).click();
  await expect(studio.locator("tfoot")).toContainText("1,543,714,304");
  const downloading = page.waitForEvent("download");
  await studio.getByRole("button", { name: "导出分析 JSON" }).click();
  const download = await downloading;
  const exported = JSON.parse(await fs.readFile((await download.path())!, "utf8"));
  expect(exported.totals.total).toBe(1543714304);
  await studio.getByRole("button", { name: "来源与审计", exact: true }).click();
  await expect(studio.locator(".source-view")).toContainText("8faed761d45a263340a0528343f099c05c9a4323");
  await expect(studio.locator(".glossary")).toBeVisible();
  await studio.getByRole("button", { name: "算子成本", exact: true }).click();
  await studio.getByRole("button", { name: "计算", exact: true }).click();
  await expect(studio.locator(".cost-summary")).toContainText("Roofline");
  await page.screenshot({ path: `${evidence}/studio-cost-${info.project.name}.png`, fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  expect(overflow).toBe(false);
  await page.reload();
  await expect(studio.getByRole("heading", { name: /算子成本/ })).toBeVisible();
  const models = await (await request.get("/api/models")).json();
  const other = models.find((item: { repo_id: string }) => item.repo_id === "Qwen/Qwen2.5-0.5B");
  await page.goto(`/models/${other.id}?tab=structure`);
  await expect(studio.locator(".metrics-strip")).toContainText("494,032,768");
  await page.goto(`/models/${other.id}?tab=structure&snapshot=${before}`);
  await expect(studio.getByRole("alert")).toContainText("not found");
  expect(errors).toEqual([]);
  expect(requests.filter(url => /:(5173|18761)\b|\/v[12]\//.test(url))).toEqual([]);
  await fs.writeFile(`${evidence}/studio-network-${info.project.name}.json`, JSON.stringify({ errors, requests }, null, 2));
});

test("transplanted studio tablet graph sizing", async ({ page }, info) => {
  test.skip(info.project.name !== "desktop", "Tablet is an additional desktop viewport.");
  await page.setViewportSize({ width: 1024, height: 900 });
  await page.goto(`/models/${model}?tab=structure`);
  await expect(page.locator(".react-flow__node").first()).toBeVisible();
  const rect = await page.locator(".flow-wrap").boundingBox();
  expect(rect!.width).toBeGreaterThan(500);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1025);
  await page.screenshot({ path: `${evidence}/studio-tablet.png`, fullPage: true });
});
